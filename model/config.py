#          確保するため「接近のない揺れ中心のウィンドウ」への偏向を防ぐ。
#        区間が1ウィンドウに収まる場合はウィンドウ1つ（重み1） = 'pre' と同一。RC衝突（12〜20フレーム）は接近
#        15を加算して27〜35フレームとなりウィンドウ1〜2つ（2つでも1〜5フレーム差）のため実質 'pre' と同一、
#        realdata は大半がウィンドウ2〜6個となる。
