# "span": 接近（衝突開始 PRE フレーム前）から衝突終了までを複数の30フレームウィンドウで網羅し、
#        そのウィンドウを「全件」Aとして学習しつつ、衝突1件あたりの重み合計は1に正規化する。
#          · 先頭ウィンドウ（接近 + 衝突開始, = 'pre' のウィンドウ） : TRAIN_SPAN_FIRST_WEIGHT (既定 ½)
#          · 残りのウィンドウ（衝突終端側）                         : 残余の重みを均等に分配 (5ウィンドウなら各 1/10)
