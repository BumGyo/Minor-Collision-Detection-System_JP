# ---------- 衝突(A)クリップのスライシング ----------
# Aは元来動画あたり1クリップ（start_f 基準で30フレーム）のみ投入していた。しかしラベル付けされた衝突
# 区間は中央値32フレーム・最大143フレームであり、長尺の衝突の大部分が学習で破棄されていた。
# Sは動画全体を切り出して投入するため（後述）、A:Sが 1:10.4 まで拡大しモデルが「全件S」へ
# 崩壊する現象が発生した（実測: 3エポック連続で A recall 0.000）。
# ここでは**ラベル区間 [start_f, end_f] 内に限定して**ウィンドウをスライドさせ Aクリップを増強する。
#   · 区間外には決してはみ出さない（はみ出せば不正なラベルを学習させることになる）。
#   · 最終ウィンドウは end_f に整合させる — 論文で最高性能を記録した「衝突終了基準」クリップ。
# stride 15 基準で A 58 → 203クリップ、不均衡 1:10.4 → 1:3.0。
# ※ 無効化時は False（従来動作 = 動画あたり1クリップ）
