# クラス重み(CrossEntropyLoss weight)。SスライシングによりA:Sの不均衡が拡大すると
# モデルがSへ偏向し「未検出」が増加する恐れがある。（なし=None, 例: (1.0, 3.0) → Aを3倍）
# ※ 検証なしでの有効化は厳禁 — 設定値によって誤検知が急増するリスクがある。
#
# 実測: Aスライシング有効時でも A:S ≈ 1:12.9 (rcdata 833 + realdata 基準)。
