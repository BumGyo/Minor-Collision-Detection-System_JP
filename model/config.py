# ---------- イベント後処理 (分断防止 / チャタリング除去) ----------
# モデル判定が A→S→A とチャタリングすると1件の衝突が複数イベントに分断される（実測: 実車動画
# 1件が6個に分断）。下記の2ステップで整理する。順序は「結合 → 長さフィルタ」。
#   1) 間隔の近いイベントは同一事故とみなして結合
#   2) それでも極端に短い（単発チャタリング）イベントは除外
# 結合間隔は「秒」で定義し、動画fpsによりフレーム換算する。ユーザーにとって重要なのは衝突が
# 「開始された地点」であり、数秒以内に再度判定が発生した場合は同一事故の継続とみなすのが自然である。
# フレーム数で固定するとfps(10〜60)により同一値が9秒〜1.5秒に変動してしまう。
# 3秒 = 30fps基準で90フレーム。（旧設定値: 45フレーム ≈ 1.5秒）
PREDICT_EVENT_MERGE_GAP_SEC = 3.0
# 最小長 — イベント長 = 28 + (A と判定された連続ウィンドウ数)  [stride 1 基準]
#   · ウィンドウが30フレームのため、Aウィンドウが1個のみでも29フレームとなる。そのため29以下に設定するとフィルタを
#     無効化したのと同義になる。
#   · イベント長は「衝突が実際に持続した時間」ではない。短い衝突であってもそのシーンを含む
#     ウィンドウが30個存在するため、モデルが検出した場合は複数ウィンドウが連続してAとなる。
#   · 実測（x3d-ptY 33ep、選別無効）: 真の衝突14件の連続 A ウィンドウ数は 30〜220、単発誤検知は約5件。
#     35（連続7ウィンドウ）と40（12ウィンドウ）はこのデータにおいて結果が同一であった。微弱に検出された微小衝突は
#     連続ウィンドウが30未満となる可能性があるため、見逃し防止にマージンを持たせた 35 を採用。
