# 値の選定: 逆頻度比そのまま(12.9)では誤検知急増リスクが高いため平方根緩和値を採用。
#   sqrt(12.9) ≈ 3.6。それでも recall が0の場合は 12.9 方向へ引き上げる。
# → S間隔90（A:S約 1:7.1）の間は損失重み付けを無効化。2026-10-12 間隔を30に変更し
#   約 1:18.6 となったが、まずは重みなしで学習を試行。val_real recall が0に留まる場合は
